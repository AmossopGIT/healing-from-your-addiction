import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const files = [
  "content/admin-docs/how-to-add-pages.md",
  "content/admin-docs/meeting-notes-index.md",
  "content/admin-docs/meeting-2026-08-31-pricing-lead-nurture.md",
  "content/admin-docs/meeting-notes-template.md",
  "content/admin-docs/plan-2026-08-31-product-ladder.md",
  "docs/CMS_BLOG_ADMIN.md",
  "docs/MARKETING_GERALD_CHECKLIST.md",
  "docs/DEPLOY_PRODUCTION.md",
];

const entries = files
  .map((rel) => {
    const absolute = path.join(root, rel);
    if (!fs.existsSync(absolute)) {
      throw new Error(`Missing admin doc markdown: ${rel}`);
    }
    const raw = fs.readFileSync(absolute, "utf8");
    return `  ${JSON.stringify(rel)}: ${JSON.stringify(raw)},`;
  })
  .join("\n");

const out = `/**
 * Auto-generated by scripts/generate-admin-doc-markdown.mjs — do not edit by hand.
 * Markdown is inlined so Vercel/Turbopack can serve admin docs without fs tracing.
 */
export const adminDocMarkdownBySourcePath: Record<string, string> = {
${entries}
};

export function getBundledAdminDocMarkdown(sourcePath: string): string | null {
  return adminDocMarkdownBySourcePath[sourcePath] ?? null;
}
`;

const target = path.join(root, "lib/adminDocs/markdownSources.ts");
fs.writeFileSync(target, out);
console.log(`Wrote ${path.relative(root, target)} (${files.length} docs)`);
